CREATE TABLE advertising_types (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,
    code VARCHAR(30) NOT NULL,
    name VARCHAR(100) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT pk_advertising_types PRIMARY KEY (id),
    CONSTRAINT ck_advertising_types_code_not_blank CHECK (BTRIM(code) <> ''),
    CONSTRAINT ck_advertising_types_name_not_blank CHECK (BTRIM(name) <> ''),
    CONSTRAINT ck_advertising_types_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE UNIQUE INDEX uk_advertising_types_code_lower
    ON advertising_types (LOWER(code));

